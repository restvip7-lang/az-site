/** Service markup (spec 9: Service + FAQPage on service pages). */
export function serviceLd(s: ServiceDef, url: string) {
  return {
    "@context": "https://schema.org",
    "@type": "Service",
    name: s.name,
    serviceType: s.name,
    description: s.description || s.short,
    url: `${SITE_URL}${url}`,
    areaServed: { "@type": "Country", name: "Турция" },
    provider: { "@id": `${SITE_URL}/#organization` },
  };
}
